import {
  BarDataSet,
  CartesianGrid,
  Chart,
  Column,
  Container,
  Document,
  Expanded,
  FixedAxis,
  FixedColumnWidth,
  FlexColumnWidth,
  MultiPage,
  PointChartValue,
  Row,
  TableHelper,
  Text,
  TextStyle
} from '../dist/js_pdf.mjs';

export function createSalesReport(model) {
  const document = new Document({
    title: 'Sales Report',
    author: model.author ?? 'Blunana',
    subject: 'Executive Dashboard'
  });

  document.addPage(
    new MultiPage({
      margin: 32,
      gap: 10,

      header: context => new Row({
        widths: [3, 1],
        children: [
          new Text('SALES REPORT', {
            fontSize: 16,
            color: '#172554'
          }),
          new Text(`Page ${context.pageNumber}`, {
            align: 'right',
            color: '#64748b'
          })
        ]
      }),

      footer: () => new Text('Generated by js_pdf', {
        fontSize: 9,
        color: '#64748b',
        align: 'center'
      }),

      build: () => [
        new Text(model.period, {
          fontSize: 11,
          color: '#64748b'
        }),

        new Row({
          gap: 8,
          children: [
            new Expanded({ child: metricCard('Revenue', formatMoney(model.revenue)) }),
            new Expanded({ child: metricCard('Orders', String(model.orders)) }),
            new Expanded({ child: metricCard('Average order value', formatMoney(model.averageTicket)) })
          ]
        }),

        new Container({
          padding: 12,
          borderColor: '#dbeafe',
          background: '#eff6ff',
          child: new Column({
            gap: 8,
            children: [
              new Text('Monthly revenue', {
                fontSize: 14,
                color: '#1e3a8a'
              }),
              createBarChart(model.months)
            ]
          })
        }),

        new Text('Sales details', {
          fontSize: 15,
          color: '#172554',
          margin: { top: 6, bottom: 2 }
        }),

        createSalesTable(model.sales)
      ]
    })
  );

  return document.save();
}

function metricCard(label, value) {
  return new Container({
    padding: 10,
    background: '#f8fafc',
    borderColor: '#cbd5e1',
    alignment: 'center',
    child: new Column({
      gap: 4,
      crossAxisAlignment: 'center',
      children: [
        new Text(label, {
          fontSize: 9,
          color: '#64748b',
          align: 'center'
        }),
        new Text(value, {
          fontSize: 17,
          color: '#0f172a',
          align: 'center'
        })
      ]
    })
  });
}

function createBarChart(items) {
  const maxValue = Math.max(1, ...items.map(item => Number(item.value) || 0));
  const axisMaximum = Math.ceil(maxValue / 10000) * 10000;
  const axisStep = axisMaximum / 4;
  const tickStyle = new TextStyle({ fontSize: 8, color: '#475569' });

  return new Container({
    height: 180,
    child: new Chart({
      grid: new CartesianGrid({
        xAxis: FixedAxis.fromStrings(items.map(item => item.label), {
          textStyle: tickStyle,
          color: '#94a3b8',
          marginStart: 24,
          marginEnd: 24,
          ticks: true
        }),
        yAxis: new FixedAxis([0, axisStep, axisStep * 2, axisStep * 3, axisMaximum], {
          textStyle: tickStyle,
          color: '#94a3b8',
          divisions: true,
          divisionsColor: '#cbd5e1',
          format: value => value === 0 ? '$0' : `$${value / 1000}k`
        })
      }),
      datasets: [
        new BarDataSet({
          color: '#2563eb',
          drawBorder: false,
          width: 24,
          data: items.map((item, index) => new PointChartValue(index, Number(item.value) || 0))
        })
      ]
    })
  });
}

function createSalesTable(sales) {
  return TableHelper.fromTextArray({
    headers: [
      'Date',
      'Customer',
      alignedTableText('Status', 'center', '#ffffff', 'bold'),
      alignedTableText('Amount', 'centerRight', '#ffffff', 'bold')
    ],
    data: sales.map(sale => [
      sale.date,
      sale.customer,
      sale.status,
      formatMoney(sale.value)
    ]),
    border: null,
    columnWidths: {
      0: new FixedColumnWidth(72),
      1: new FlexColumnWidth(3),
      2: new FlexColumnWidth(1.2),
      3: new FixedColumnWidth(76)
    },
    headerStyle: new TextStyle({
      fontSize: 11,
      fontWeight: 'bold',
      color: '#ffffff'
    }),
    cellStyle: new TextStyle({ fontSize: 10, color: '#334155' }),
    headerDecoration: { color: '#1e3a8a' },
    rowDecoration: {
      color: '#ffffff',
      border: { bottom: { color: '#e2e8f0', width: 0.6 } }
    },
    oddRowDecoration: {
      color: '#f8fafc',
      border: { bottom: { color: '#e2e8f0', width: 0.6 } }
    },
    cellPadding: 7,
    cellHeight: 24,
    headerHeight: 27,
    cellAlignments: { 2: 'center', 3: 'centerRight' },
    headerAlignments: { 2: 'center', 3: 'centerRight' },
    cellBuilder: (column, value) => {
      if (column === 2) {
        return alignedTableText(
          value,
          'center',
          value === 'Paid' ? '#15803d' : '#b45309'
        );
      }
      if (column === 3) {
        return alignedTableText(value, 'centerRight');
      }
      return null;
    }
  });
}

function alignedTableText(value, alignment, color = '#334155', fontWeight = 'normal') {
  return new Container({
    alignment,
    child: new Text(String(value), {
      fontSize: 9,
      fontWeight,
      color,
      align: alignment === 'centerRight' ? 'right' : 'center'
    })
  });
}

function formatMoney(value) {
  const [integer, decimal] = Number(value).toFixed(2).split('.');
  const grouped = integer.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return `$${grouped}.${decimal}`;
}
